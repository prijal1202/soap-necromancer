package dev.soapnecromancer.generators;

import dev.soapnecromancer.runtime.model.OperationModel;
import dev.soapnecromancer.runtime.model.ServiceModel;
import dev.soapnecromancer.runtime.model.SoapVersion;

import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;

import static dev.soapnecromancer.generators.JsonSchemas.map;

/**
 * Generator: canonical model -> {@code openapi.yaml} (OpenAPI 3.0.3) describing
 * the generated proxy.
 * Built directly from the model, no swagger-models. Generators spec,
 * Requirement 1.
 */
public final class OpenApiGenerator {
    public static final String PROBLEM = "Problem";
    static final String DEFAULT_SERVER = "http://localhost:8080";
    private static final String REF = "#/components/schemas/";

    public String generate(ServiceModel model) {
        JsonSchemas schemas = new JsonSchemas(model, Set.of(PROBLEM), REF, false);

        Map<String, Object> doc = new LinkedHashMap<>();
        doc.put("openapi", "3.0.3");
        doc.put("info", map(
                "title", model.name(),
                "version", "1.0.0",
                "description", "REST API of the generated proxy for SOAP service " + model.name()
                        + " (target namespace " + model.targetNamespace() + "). Each operation accepts JSON,"
                        + " calls the SOAP " + model.soapVersion().label()
                        + " endpoint, and returns the response as JSON."
                        + " Generated by SOAP Necromancer."));
        doc.put("servers", List.of(map("url", DEFAULT_SERVER, "description", "generated proxy")));

        Map<String, Object> paths = new LinkedHashMap<>();
        for (OperationModel op : model.operations()) {
            paths.put("/" + op.name(), map("post", operation(op, model.soapVersion(), schemas)));
        }
        doc.put("paths", paths);

        Map<String, Object> components = new LinkedHashMap<>();
        for (String typeId : schemas.names().keySet()) {
            components.put(schemas.names().get(typeId), schemas.definition(typeId));
        }
        components.put(PROBLEM, problemSchema());
        doc.put("components", map("schemas", components));

        return "# Generated by SOAP Necromancer (generator). Describes the generated proxy; do not edit.\n"
                + Yaml.write(doc);
    }

    private static Map<String, Object> operation(OperationModel op, SoapVersion version, JsonSchemas schemas) {
        Map<String, Object> o = new LinkedHashMap<>();
        o.put("operationId", op.name());
        if (!op.documentation().isEmpty())
            o.put("summary", op.documentation());
        String actionLabel = version == SoapVersion.SOAP_11 ? "SOAPAction" : "SOAP 1.2 action";
        String soapAction = op.soapAction().isEmpty() ? "" : " (" + actionLabel + " " + op.soapAction() + ")";
        o.put("description", "Calls SOAP operation " + op.name() + soapAction + ".");
        o.put("requestBody", map("required", true,
                "content", map("application/json", map("schema", schemas.reference(op.input().typeId())))));

        Map<String, Object> responses = new LinkedHashMap<>();
        responses.put("200", map("description", "SOAP response converted to JSON",
                "content", map("application/json", map("schema", schemas.reference(op.output().typeId())))));
        responses.put("400", problem("Invalid request JSON, or a SOAP " + Faults.client(version) + " fault"));
        responses.put("502", problem("SOAP " + Faults.server(version)
                + " fault, unreadable SOAP response, or endpoint unreachable"));
        responses.put("504", problem("SOAP endpoint timed out"));
        o.put("responses", responses);
        return o;
    }

    private static Map<String, Object> problem(String description) {
        return map("description", description,
                "content", map("application/problem+json", map("schema", map("$ref", REF + PROBLEM))));
    }

    /**
     * RFC 7807 body plus the JSON path and SOAP fault fields the generated proxy
     * adds.
     */
    private static Map<String, Object> problemSchema() {
        Map<String, Object> props = new LinkedHashMap<>();
        props.put("type", map("type", "string"));
        props.put("title", map("type", "string"));
        props.put("status", map("type", "integer", "format", "int32"));
        props.put("detail", map("type", "string"));
        props.put("path", map("type", "string", "description", "JSON path of the invalid request value"));
        props.put("faultcode", map("type", "string"));
        props.put("faultstring", map("type", "string"));
        return map("type", "object", "properties", props);
    }
}
